function mediaOf(u){
  const m = UNIT_MEDIA[u.unit] || {};
  void u;
  const photos = (m.photos || []).slice(0, MAX_PHOTOS);
  const asis = m.asis || [];   // 1-based numbers of photos shown as the room is today (no virtual staging)
  const st = UNIT_STORIES[u.unit];
  const staged = asis.length > 0 && !!st && st.en.concept.actual === false;
  const skip = IDEA_SKIP[u.unit] || [];
  const furnished = u.furniture === "Fully Furnished";    // sold with every piece in the photos: no styling remark
  const items = photos.map((src, i) => ({ kind: "photo", src, asis: asis.includes(i + 1),
    idea: !furnished && (m.idea ? m.idea.includes(i + 1) : staged && !asis.includes(i + 1) && !skip.includes(i + 1)) }));
  const poster = m.poster || photos[0] || "";
  if (m.video) items.push({ kind: "video", src: m.video, poster });
  else if (m.youtube) items.push({ kind: "yt", src: m.youtube, poster });
  const lay = m.plan ? null : layoutOf(u);
  if (m.plan) items.push({ kind: "plan", src: m.plan });
  else if (lay) items.push({ kind: "plan", src: lay.src, code: lay.code });
  const planSrc = m.plan || (lay && lay.src) || "";
  return { photos, items, hasVideo: !!(m.video || m.youtube), hasPlan: !!planSrc, planSrc, updated: m.updated || "" };
}

