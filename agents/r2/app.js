function drawQR(ctx, text, x, y, size){
  if (typeof qrcode !== "function") return false;
  try {
    const qr = qrcode(0, "M"); qr.addData(text); qr.make();
    const n = qr.getModuleCount(), pad = Math.round(size * 0.07), cell = (size - pad * 2) / n;
    ctx.fillStyle = "#fff"; ctx.fillRect(x, y, size, size);
    ctx.fillStyle = "#0B1F25";
    for (let r = 0; r < n; r++) for (let c = 0; c < n; c++)
      if (qr.isDark(r, c)) ctx.fillRect(x + pad + c * cell, y + pad + r * cell, Math.ceil(cell), Math.ceil(cell));
    return true;
  } catch (e) { return false; }
}
async function buildSocialImage(u, opts){
  const S = SOC_T[soc.lg] || SOC_T.en, lg = soc.lg;
  const [W, H] = SOC_RATIOS[soc.ratio] || SOC_RATIOS["4:5"];
  const PAD = 56;
  const cv = document.createElement("canvas"); cv.width = W; cv.height = H;
  const ctx = cv.getContext("2d");
  try { await document.fonts.ready; } catch (e) {}
  const F = (w, sz, mono) => `${w} ${sz}px ${mono ? "'IBM Plex Mono', ui-monospace, monospace" : "'IBM Plex Sans Thai', system-ui, sans-serif"}`;

  /* photo, kept bright — only the caption band below is darkened */
  const bgs = socBgList(u), bg = bgs.length ? await loadImg(bgs[soc.img % bgs.length]) : null;
  ctx.fillStyle = "#123038"; ctx.fillRect(0, 0, W, H);
  if (bg){
    const s2 = Math.max(W / bg.width, H / bg.height), w = bg.width * s2, h = bg.height * s2;
    ctx.filter = "brightness(1.06) saturate(1.04)";
    ctx.drawImage(bg, (W - w) / 2, (H - h) / 2, w, h);
    ctx.filter = "none";
  }
  let g = ctx.createLinearGradient(0, 0, 0, H * 0.2);                    // just enough for the logo
  g.addColorStop(0, "rgba(6,28,34,.55)"); g.addColorStop(1, "rgba(6,28,34,0)");
  ctx.fillStyle = g; ctx.fillRect(0, 0, W, H * 0.2);

  /* ---- caption band: measure every line first, then lay them out top-down ---- */
  const d = u.promoPrice ? Math.round(discount(u) * 100) : 0;
  const rows = [];
  rows.push({ t: PROJECT_NAME.toUpperCase(), f: F(700, 26), c: "rgba(255,255,255,.72)", h: 30, gap: 10, sp: 2 });
  rows.push({ t: u.unit, f: F(600, 74, true), c: "#fff", h: 78, gap: 8 });
  rows.push({ t: `${tl("floorWord", lg)} ${u.floor} · ${sqmFmt(u.sqm)} ${tl("thSqm", lg)} · ${tl(typeLabel(u), lg)}`,
              f: F(500, 36), c: "rgba(255,255,255,.9)", h: 44, gap: 14 });
  if (opts.price){
    const big = soc.ratio === "1:1" ? 84 : 92;
    rows.push({ t: baht(sell(u)), f: F(600, big, true), c: "#F0866B", h: big + 4, gap: 10 });
    if (d && opts.disc) rows.push({ kind: "old", f: F(500, 32, true), f2: F(600, 30), h: 38, gap: 0 });
  }
  const bandH = rows.reduce((a, r) => a + r.h + (r.gap || 0), 0) + PAD * 2;
  const fade = 150;
  g = ctx.createLinearGradient(0, H - bandH - fade, 0, H - bandH);
  g.addColorStop(0, "rgba(6,28,34,0)"); g.addColorStop(1, "rgba(6,28,34,.9)");
  ctx.fillStyle = g; ctx.fillRect(0, H - bandH - fade, W, fade);
  ctx.fillStyle = "rgba(6,28,34,.9)"; ctx.fillRect(0, H - bandH, W, bandH);

  /* QR sits inside the band, on the right */
  const qrMax = Math.min(210, bandH - 56);
  const hasQR = opts.qr && drawQR(ctx, socUrl(u), W - PAD - qrMax, H - bandH + (bandH - qrMax) / 2, qrMax);
  const textW = W - PAD * 2 - (hasQR ? qrMax + 40 : 0);

  const fit = (text, font, max) => {                                     // shrink a line until it fits
    let size = parseInt(font.match(/(\d+)px/)[1], 10);
    ctx.font = font;
    while (ctx.measureText(text).width > max && size > 18){
      size -= 2; ctx.font = font.replace(/\d+px/, size + "px");
    }
    return ctx.font;
  };
  ctx.textAlign = "left"; ctx.textBaseline = "top";
  let y = H - bandH + PAD;
  for (const r of rows){
    if (r.kind === "old"){
      ctx.font = fit(baht(u.price), r.f, textW * 0.45); ctx.fillStyle = "rgba(255,255,255,.7)";
      const old = baht(u.price), ow = ctx.measureText(old).width;
      ctx.fillText(old, PAD, y);
      ctx.strokeStyle = "rgba(255,255,255,.7)"; ctx.lineWidth = 3;
      ctx.beginPath(); ctx.moveTo(PAD, y + r.h * 0.45); ctx.lineTo(PAD + ow, y + r.h * 0.45); ctx.stroke();
      ctx.font = fit(`−${d}%  ${S.save} ${baht(u.price - sell(u))}`, r.f2, textW - ow - 30); ctx.fillStyle = "#F0866B";
      ctx.fillText(`−${d}%  ${S.save} ${baht(u.price - sell(u))}`, PAD + ow + 26, y + 2);
    } else {
      ctx.font = fit(r.t, r.f, textW); ctx.fillStyle = r.c;
      if (r.sp){                                                         // letter-spaced eyebrow
        let x = PAD;
        for (const ch of r.t){ ctx.fillText(ch, x, y); x += ctx.measureText(ch).width + r.sp; }
      } else ctx.fillText(r.t, PAD, y);
    }
    y += r.h + (r.gap || 0);
  }

  const logo = await loadImg("riviera-img/logo-bar-pale.png");           // brand, top-left
  if (logo) ctx.drawImage(logo, PAD, 52, 330, 330 * logo.height / logo.width);

  const badge = u.promoPrice ? S.promoTag : tl(viewLabel(u), lg);        // tag, top-right
  ctx.textBaseline = "middle"; ctx.textAlign = "center";
  ctx.font = F(700, 30);
  const bw = ctx.measureText(badge).width + 56;
  ctx.fillStyle = u.promoPrice ? "#C0442B" : "rgba(11,31,37,.72)";
  ctx.beginPath(); ctx.roundRect(W - PAD - bw, 54, bw, 62, 31); ctx.fill();
  ctx.fillStyle = "#fff"; ctx.fillText(badge, W - PAD - bw / 2, 86);
  return cv;
}

