/* Typical floor plate, from the sales kit's "Typical Room Number Layout":
   front (sea) line — A1–6, B1–9, C1–8, then the angled D wing 1–4;
   rear (city) line — E1–12 beneath towers B and C. */
function floorPlate(){
  const W = 26, H = 30, GAP = 9, cells = [], pos = {};
  let x = 0;
  [["A", 6], ["B", 9], ["C", 8]].forEach(([t, n]) => {
    for (let i = 1; i <= n; i++){ const id = t + String(i).padStart(2, "0"); pos[id] = x; cells.push({ id, t, n: i, x, y: 0 }); x += W; }
    x += GAP;
  });
  const dx = x - GAP + 10;
  const rear = [["E01","B01"],["E02","B02"],["E03","B03"],["E04","B04"],["E05","B05"],["E06","B07"],["E07","B08"],["E08","B09"],["E09","C01"],["E10","C03"],["E11","C06"],["E12","C07"]];
  const yR = H + 16;
  rear.forEach(([id, over]) => cells.push({ id, t: "E", n: +id.slice(1), x: pos[over], y: yR }));
  for (let i = 1; i <= 4; i++) cells.push({ id: "D0" + i, t: "D", n: i, x: (i - 1) * W, y: 0, wing: true });
  return { W, H, cells, dx, width: dx + 4 * W + 40, yR };
}

function plateSVG(u){
  const m = /([A-E])(\d{2})$/.exec(u.unit), here = m ? m[1] + m[2] : "";
  const { W, H, cells, dx, width, yR } = floorPlate();
  const cell = c => {
    const on = c.id === here;
    return `<g><rect x="${c.x}" y="${c.y}" width="${W - 2}" height="${H}" rx="3"
      fill="${on ? "var(--coral)" : c.t === "E" ? "var(--surface)" : "var(--sea-soft)"}"
      stroke="${on ? "var(--coral)" : "var(--line-2)"}" stroke-width="1"/>
      <text x="${c.x + (W - 2) / 2}" y="${c.y + H / 2 + 4}" text-anchor="middle" font-size="10"
      fill="${on ? "#fff" : "var(--muted)"}" font-weight="${on ? 700 : 400}">${c.n}</text></g>`;
  };
  const flat = cells.filter(c => !c.wing), wing = cells.filter(c => c.wing);
  const towerLabel = (t, cx, y) => `<text x="${cx}" y="${y}" text-anchor="middle" font-size="11" font-weight="700" fill="var(--ink-2)">${t}</text>`;
  const mid = t => { const xs = flat.filter(c => c.t === t).map(c => c.x); return (Math.min(...xs) + Math.max(...xs) + W - 2) / 2; };
  const hc = cells.find(c => c.id === here);
  let callout = "";
  if (hc){
    const cx = hc.wing ? dx + (hc.x + (W - 2) / 2) * Math.cos(22 * Math.PI / 180) : hc.x + (W - 2) / 2;
    const top = hc.y === 0;
    callout = top
      ? `<g transform="translate(${cx},-22)"><rect x="-26" y="-13" width="52" height="18" rx="9" fill="var(--coral)"/><text y="0" text-anchor="middle" font-size="11" font-weight="700" fill="#fff">${u.unit}</text></g>`
      : `<g transform="translate(${cx},${yR + H + 24})"><rect x="-26" y="-13" width="52" height="18" rx="9" fill="var(--coral)"/><text y="0" text-anchor="middle" font-size="11" font-weight="700" fill="#fff">${u.unit}</text></g>`;
  }
  return `<svg viewBox="-12 -42 ${width + 24} ${yR + H + 72}" role="img" aria-label="${t("uLocation")} ${u.unit}">
    <text x="-6" y="-30" font-size="10.5" font-weight="700" letter-spacing=".08em" fill="var(--sea)">${t("uSeaSide").toUpperCase()} ↑</text>
    ${flat.map(cell).join("")}
    <g transform="translate(${dx},0) rotate(22)">${wing.map(cell).join("")}</g>
    ${["A", "B", "C"].map(tw => towerLabel(tw, mid(tw), H + 12)).join("")}
    ${towerLabel("D", dx + 2 * W, H + 40)}
    ${towerLabel("E", (flat.find(c => c.id === "E01").x + flat.find(c => c.id === "E12").x) / 2, yR + H + 13)}
    <text x="-6" y="${yR + H + 42}" font-size="10.5" font-weight="700" letter-spacing=".08em" fill="var(--muted)">${t("uCitySide").toUpperCase()} ↓</text>
    ${callout}
  </svg>`;
}

