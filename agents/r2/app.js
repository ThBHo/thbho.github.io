/* ------------------------------ filter --------------------------- */
function filtered(){
  const q = state.q.trim().toUpperCase();
  let list = UNITS.filter(u => {
    if (q && !u.unit.toUpperCase().includes(q)) return false;
    if (state.view && u.view !== state.view) return false;
    if (state.type && u.type !== state.type) return false;
    if (state.quota && u.quota !== state.quota) return false;
    if (state.floor && u.floor !== state.floor) return false;
    if (state.promo && !u.promoPrice) return false;
    if (state.furn && !isFurnished(u)) return false;
    if (state.savedOnly && !saved.has(u.unit)) return false;
    return true;
  });
  const cmp = {
    priceAsc: (a,b) => sell(a) - sell(b),
    priceDesc: (a,b) => sell(b) - sell(a),
    perSqm: (a,b) => perSqm(a) - perSqm(b),
    sqm: (a,b) => b.sqm - a.sqm,
    floor: (a,b) => floorKey(b.floor) - floorKey(a.floor),
    save: (a,b) => discount(b) - discount(a)
  }[state.sort];
  if (!cmp) return recommended(list.filter(u => u.status !== "SOLD")).concat(list.filter(u => u.status === "SOLD"));
  list.sort((a,b) => (a.status === "SOLD") - (b.status === "SOLD") || cmp(a,b));
  return list;
}

/* "Recommended" (the default order): the most complete units first — photos, a story
   (MBTI, feng shui, concept), a floor plan, a video, furniture — picked so each block of
   PAGE_SIZE mixes room type, view, floor band, tower and MBTI group. The first block
   leaves out the featured units (they already have their own row above). The grid
   shows PAGE_SIZE cards at a time, with + / − to show more or fewer. */
const PAGE_SIZE = 12;
function unitScore(u){
  const m = mediaOf(u);
  return Math.min(m.photos.length, 8) * 2 + (UNIT_STORIES[u.unit] ? 12 : 0) + (m.hasPlan ? 3 : 0) + (m.hasVideo ? 2 : 0)
    + (u.furniture !== "Exclude" ? 2 : 0) + (u.promoPrice ? 2 : 0);
}
function diversityKeys(u){
  const st = UNIT_STORIES[u.unit], g = st && st.mbti ? mbtiGroup(st.mbti[0]) : "", f = parseInt(u.floor, 10) || 0;
  return ["t" + u.type, "v" + u.view, "f" + (f < 12 ? 0 : f < 25 ? 1 : 2), "w" + u.unit.replace(/^\d+/, "").charAt(0), ...(g ? ["g" + g] : [])];
}
function recommended(list){
  const left = list.map(u => ({ u, s: unitScore(u), k: diversityKeys(u), hl: HIGHLIGHTS.units.includes(u.unit) }));
  const out = [];
  let seen = {};
  while (left.length){
    if (out.length % PAGE_SIZE === 0) seen = {};
    const first = out.length < PAGE_SIZE && left.some(x => !x.hl);
    let bi = -1, bv = -Infinity;
    left.forEach((x, i) => {
      if (first && x.hl) return;
      const v = x.s - x.k.reduce((p, k) => p + (seen[k] || 0) * 2.5, 0);
      if (v > bv){ bv = v; bi = i; }
    });
    const [x] = left.splice(bi, 1);
    x.k.forEach(k => { seen[k] = (seen[k] || 0) + 1; });
    out.push(x.u);
  }
  return out;
}

